// The guide output is split in two tiers (INV-001):
//
//   - Writer rules: the always-loaded file every agent reads on every turn
//     (.claude/rules/verikt-index.md, AGENTS.md section, .cursor/rules/verikt.mdc,
//     copilot, windsurf). It stays within INV-001's instruction and token budget
//     and points to the references below.
//   - References: on-demand files under .verikt/references/ that the agent reads
//     only when the task calls for them (catalog dumps, reviewer checklists,
//     full layer/anti-pattern detail, and — in catalog-only output, for a
//     project with nothing scaffolded yet — the scaffold interview protocol).
//
// Both tiers are derived from verikt.yaml only; nothing here scans the
// project's source tree (ADR-008).

// referencesDir is the project-relative directory holding on-demand references.
const referencesDir = ".verikt/references"

// referenceSpec names one on-demand reference file and when the agent should read it.
type referenceSpec struct {
	file string
	when string
}

var (
	refArchitecture = referenceSpec{file: "architecture.md", when: "before adding a package or file, or an import that crosses a layer"}
	refCapabilities = referenceSpec{file: "capabilities.md", when: "before adding or wiring a capability (transport, data, resilience, security)"}
	refReview       = referenceSpec{file: "review.md", when: "before you finish a change, and when reviewing code"}
	refInterview    = referenceSpec{file: "interview.md", when: "when the user asks to scaffold a new service"}
)

// allReferenceSpecs lists every reference verikt may write, so stale ones from
// a previous run (e.g. interview.md once a catalog-only project gets a
// verikt.yaml) can be removed. --catalog-only refuses in a configured project,
// so it never removes architecture.md.
var allReferenceSpecs = []referenceSpec{refArchitecture, refCapabilities, refReview, refInterview}

// referenceSpecs returns the references produced for opts, in reading order.
//
// The scaffold interview is produced only in catalog-only output: a guide
// generated from verikt.yaml describes an architecture that already exists, so
// instructions for scaffolding a new one steer nothing (INV-001).
func referenceSpecs(opts GenerateOptions) []referenceSpec {
	if opts.CatalogOnly {
		return []referenceSpec{refCapabilities, refReview, refInterview}
	}
	return []referenceSpec{refArchitecture, refCapabilities, refReview}
}

func referencePath(spec referenceSpec) string {
	return referencesDir + "/" + spec.file
}

// buildReferences returns the content of every on-demand reference for opts,
// keyed by file name.
func buildReferences(opts GenerateOptions) map[string]string {
	out := make(map[string]string, len(allReferenceSpecs))
	for _, spec := range referenceSpecs(opts) {
		var b strings.Builder
		fmt.Fprintf(&b, "# verikt — %s\n\n", referenceTitle(spec))
		b.WriteString("> On-demand reference generated by `verikt guide` from `verikt.yaml`. Do not edit; re-run `verikt guide`.\n\n")
		switch spec {
		case refArchitecture:
			writeArchitectureReference(&b, opts)
		case refCapabilities:
			writeCapabilitiesReference(&b, opts)
		case refReview:
			writeReviewReference(&b, opts)
		case refInterview:
			writeInterviewProtocol(&b)
		}
		out[spec.file] = b.String()
	}
	return out
}

func referenceTitle(spec referenceSpec) string {
	switch spec {
	case refArchitecture:
		return "Architecture Reference"
	case refCapabilities:
		return "Capabilities Reference"
	case refReview:
		return "Review Checklist"
	default:
		return "Scaffold Interview"
	}
}

func writeArchitectureReference(b *strings.Builder, opts GenerateOptions) {
	writeArchitecture(b, opts.Architecture)
	writeLanguageVersion(b, opts.LanguageVersion, opts.Features)
	writeLayerRules(b, opts.Architecture, opts.Components)
	writeDependencyDirection(b, opts.Architecture, opts.Components)
	writeAddingCode(b, opts.Architecture)
	writeAntiPatterns(b, opts.Architecture)
}

func writeCapabilitiesReference(b *strings.Builder, opts GenerateOptions) {
	if !opts.CatalogOnly {
		writeCapabilities(b, opts.Capabilities)
		if patterns := ExtractPatterns(opts.TemplateFS, opts.Capabilities); patterns != "" {
			b.WriteString(patterns)
		}
	}
	if catalog, err := BuildCatalog(opts.TemplateFS, opts.Capabilities); err == nil && len(catalog) > 0 {
		writeCatalog(b, catalog, opts.Capabilities)
	}
	writeSmartSuggestions(b)
	writeWarnings(b, opts.Capabilities, opts.SeverityOverrides)
	writeSuggestions(b, opts.Capabilities)
}

func writeReviewReference(b *strings.Builder, opts GenerateOptions) {
	writeVerificationChecklist(b, opts.Capabilities)
	writeCriticalInteractionWarnings(b)
	writeDesignQuestions(b)
	writeDecisionStatus(b, opts.Decisions)
	writeRuleSummaries(b, opts.ProjectDir)
}

// writeReferences writes the on-demand references under projectDir and removes
// any verikt reference that this run no longer produces.
func writeReferences(projectDir string, refs map[string]string) error {
	dir := filepath.FromSlash(referencesDir)
	for _, spec := range allReferenceSpecs {
		rel := filepath.Join(dir, spec.file)
		content, ok := refs[spec.file]
		if !ok {
			if err := removeProjectFile(projectDir, rel); err != nil {
				return fmt.Errorf("remove stale reference %s: %w", spec.file, err)
			}
			continue
		}
		if err := WriteProjectFile(projectDir, rel, []byte(content)); err != nil {
			return fmt.Errorf("write reference %s: %w", spec.file, err)
		}
	}
	return nil
}

// buildWriterRules returns the always-loaded guide body shared by every target.
// It must stay within INV-001's budget: see TestGuideOutput_InstructionCount and
// TestGuideOutput_TokenBudget. Anything long or reviewer-facing belongs in a
// reference file instead.
func buildWriterRules(opts GenerateOptions) string {
	var b strings.Builder

	if opts.CatalogOnly {
		b.WriteString("# verikt — Architecture Context\n\n")
	} else {
		fmt.Fprintf(&b, "# verikt — %s Architecture\n\n", opts.Architecture)
	}
	b.WriteString("> Auto-generated by `verikt guide` from `verikt.yaml`. Do not edit; re-run `verikt guide` to update.\n\n")

	writeAgentInstructions(&b, opts.GuideMode)
	fmt.Fprintf(&b, "**Before you finish:** work through `%s`.\n\n", referencePath(refReview))
	writeGovernanceCheckpoint(&b)

	if !opts.CatalogOnly {
		b.WriteString("## Architecture: " + opts.Architecture + "\n\n")
		writeArchitectureSummary(&b, opts.Architecture)
		writeLanguageVersionCompact(&b, opts.LanguageVersion, opts.Features)
		writeLayerRulesCompact(&b, opts)
		writeActiveCapabilitiesCompact(&b, opts.Capabilities)
	}

	writeCriticalWarnings(&b, opts.Capabilities)
	writeOpenDecisionsCompact(&b, opts)
	writeActiveRulesCompact(&b, opts.ProjectDir)
	writeReferenceIndex(&b, referenceSpecs(opts))

	if opts.GuideMode == "prompted" {
		writeSuggestedPrompts(&b)
	}

	// INV-001: critical rules at the start and the end of the file.
	b.WriteString("## Before You Finish\n\n")
	b.WriteString("Run `verikt check` and fix every violation it reports: it is the build gate for this architecture. ")
	if !opts.CatalogOnly && opts.Architecture != "flat" && len(opts.Components) > 0 {
		b.WriteString("Imports must follow the layer rules above. ")
	}
	b.WriteString("Every Critical Warning that applies to your change is a MUST, because skipping it risks data loss, duplicate operations or a security breach.\n")

	return b.String()
}

// writeLanguageVersionCompact lists available language features on one line.
func writeLanguageVersionCompact(b *strings.Builder, version string, features map[string]bool) {
	if version == "" {
		return
	}
	var active []string
	for _, key := range featureOrder {
		if !features[key] {
			continue
		}
		if desc, ok := featureDescriptions[key]; ok {
			active = append(active, fmt.Sprintf("%s (%s)", key, desc.minVersion))
		}
	}
	if len(active) == 0 {
		return
	}
	b.WriteString("## Language Version\n\n")
	fmt.Fprintf(b, "%s detected. Prefer these modern APIs over legacy alternatives: %s.\n\n", version, strings.Join(active, ", "))
}

func writeLayerRulesCompact(b *strings.Builder, opts GenerateOptions) {
	if opts.Architecture == "flat" || len(opts.Components) == 0 {
		return
	}
	b.WriteString("## Layer Rules\n\n")
	for _, c := range opts.Components {
		if len(c.MayDependOn) == 0 {
			fmt.Fprintf(b, "- **%s**%s: depends on nothing (innermost)\n", c.Name, optionalSuffix(c))
		} else {
			fmt.Fprintf(b, "- **%s**%s: depends on %s\n", c.Name, optionalSuffix(c), strings.Join(c.MayDependOn, ", "))
		}
	}
	fmt.Fprintf(b, "\nWhy: dependencies point inward so business logic stays testable without infrastructure. Directory globs and forbidden imports per layer: `%s`.\n\n", referencePath(refArchitecture))
}

func writeActiveCapabilitiesCompact(b *strings.Builder, caps []string) {
	if len(caps) == 0 {
		return
	}
	names := make([]string, 0, len(caps))
	for _, c := range caps {
		names = append(names, "**"+c+"**")
	}
	b.WriteString("## Active Capabilities\n\n")
	fmt.Fprintf(b, "%s. Wiring patterns and the full catalog: `%s`.\n\n", strings.Join(names, ", "), referencePath(refCapabilities))
}

func writeOpenDecisionsCompact(b *strings.Builder, opts GenerateOptions) {
	undecided := UndecidedDecisions(opts.Decisions)
	if len(undecided) == 0 {
		return
	}
	topics := make([]string, 0, len(undecided))
	for _, d := range undecided {
		topics = append(topics, "`"+d.Topic+"`")
	}
	b.WriteString("## Open Decisions\n\n")
	fmt.Fprintf(b, "Undecided: %s. Do not implement features that depend on an undecided Tier 1 topic; ask the user or run `verikt decide`. Details: `%s`.\n\n", strings.Join(topics, ", "), referencePath(refReview))
}

// writeActiveRulesCompact names the proxy rules enforced by verikt check. The
// full table (engine, severity, scope) lives in the review reference.
func writeActiveRulesCompact(b *strings.Builder, projectDir string) {
	valid := loadValidRules(projectDir)
	if len(valid) == 0 {
		return
	}
	ids := make([]string, 0, len(valid))
	for _, r := range valid {
		ids = append(ids, "`"+r.ID+"`")
	}
	b.WriteString("## Active Rules\n\n")
	fmt.Fprintf(b, "%d proxy rules enforced by `verikt check`: %s. Engines, severities and scopes: `%s`.\n\n", len(valid), strings.Join(ids, ", "), referencePath(refReview))
}

func writeReferenceIndex(b *strings.Builder, specs []referenceSpec) {
	b.WriteString("## References (read on demand)\n\n")
	for _, spec := range specs {
		fmt.Fprintf(b, "- Read `%s` %s.\n", referencePath(spec), spec.when)
	}
	b.WriteString("\n")
}

// loadValidRules returns the valid proxy rules declared under .verikt/rules.
// These are declared configuration, not source code, so reading them keeps
// the guide normative (ADR-008).
func loadValidRules(projectDir string) []rules.Rule {
	if projectDir == "" {
		return nil
	}
	rulesDir := filepath.Join(projectDir, ".verikt", "rules")
	if _, err := os.Stat(rulesDir); err != nil {
		return nil
	}
	loaded, statuses, err := rules.LoadRules(rulesDir, projectDir)
	if err != nil {
		return nil
	}
	statusMap := make(map[string]string, len(statuses))
	for _, s := range statuses {
		statusMap[s.Rule.ID] = s.Status
	}
	var valid []rules.Rule
	for _, r := range loaded {
		if statusMap[r.ID] == "valid" {
			valid = append(valid, r)
		}
	}
	return valid
}
