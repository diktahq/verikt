// hookScriptCheck is the PostToolUse hook that runs verikt check --diff HEAD.
//
// verikt check exits non-zero when it finds blocking violations or cannot run.
// The exit code is captured explicitly: an earlier version ran the check with
// "|| true", which forced $? to 0, so the hook exited before reaching the code
// that reports violations and never reported one. Output is built with jq --arg
// so a file path cannot break or inject into the JSON document.
const hookScriptCheck = `#!/bin/bash
set -euo pipefail
# PostToolUse hook: run verikt check --diff HEAD after file edits.
# Generated by verikt guide. Do not edit manually.

if ! command -v jq >/dev/null 2>&1; then
  echo "verikt-check: jq is required but was not found on PATH" >&2
  exit 1
fi

# Read the edited file path from stdin (JSON).
TOOL_INPUT=$(cat)
FILE_PATH=$(printf '%s' "$TOOL_INPUT" | jq -r '.tool_input.file_path // empty')

if [ -z "$FILE_PATH" ]; then
  exit 0
fi

# Skip files matching check.exclude patterns.
case "$FILE_PATH" in
  */vendor/*|*/.git/*) exit 0 ;;
esac

# Run verikt check --diff HEAD scoped to changed files only. set -e is lifted
# around the call so a failing check is captured rather than aborting the hook.
set +e
RESULT=$(verikt check --diff HEAD -o json 2>/dev/null)
EXIT_CODE=$?
set -e

if [ "$EXIT_CODE" -eq 0 ]; then
  exit 0
fi

# Count every finding array verikt check -o json reports. waived[] is not a
# violation and is not counted.
COUNT=$(printf '%s' "$RESULT" | jq -r '
  ((.violations // []) | length)
  + ((.anti_patterns // []) | length)
  + ((.proxy_rules.violations // []) | length)
  + ((.decision_violations // []) | length)' 2>/dev/null) || COUNT=""
case "$COUNT" in
  ''|*[!0-9]*) COUNT=0 ;;
esac

if [ "$COUNT" -gt 0 ]; then
  MESSAGE="verikt check --diff HEAD found $COUNT violation(s) after editing $FILE_PATH. Run verikt check --diff HEAD -o terminal for details."
else
  MESSAGE="verikt check --diff HEAD failed (exit code $EXIT_CODE) after editing $FILE_PATH and produced no readable report, so architecture compliance is unverified. Run verikt check --diff HEAD -o terminal for details."
fi

# Feed the result back as context for Claude to self-correct.
jq -n --arg ctx "$MESSAGE" '{hookSpecificOutput: {hookEventName: "PostToolUse", additionalContext: $ctx}}'
exit 0
`

// hookScriptGuideRefresh is the SessionStart hook that regenerates the guide if verikt.yaml changed.
//
// sha256sum is the GNU/Linux tool and shasum the macOS one; neither exists on
// both, so the script uses whichever is present.
const hookScriptGuideRefresh = `#!/bin/bash
set -euo pipefail
# SessionStart hook: regenerate guide if verikt.yaml changed.
# Generated by verikt guide. Do not edit manually.

if [ ! -f "verikt.yaml" ]; then
  exit 0
fi

# Hash-based staleness detection. sha256sum (GNU/Linux) or shasum (macOS).
HASH_FILE=".verikt/.guide-hash"
if command -v sha256sum >/dev/null 2>&1; then
  CURRENT_HASH=$(sha256sum verikt.yaml | cut -d' ' -f1)
elif command -v shasum >/dev/null 2>&1; then
  CURRENT_HASH=$(shasum -a 256 verikt.yaml | cut -d' ' -f1)
else
  echo "verikt-guide-refresh: neither sha256sum nor shasum found; skipping guide staleness check" >&2
  exit 0
fi
STORED_HASH=$(cat "$HASH_FILE" 2>/dev/null || echo "")

if [ "$CURRENT_HASH" = "$STORED_HASH" ]; then
  exit 0  # guide is fresh
fi

if verikt guide --target claude 2>/dev/null; then
  mkdir -p .verikt
  TMP_HASH=$(mktemp "$HASH_FILE.XXXXXX")
  echo "$CURRENT_HASH" > "$TMP_HASH"
  mv "$TMP_HASH" "$HASH_FILE"
  echo '{"hookSpecificOutput": {"hookEventName": "SessionStart", "additionalContext": "verikt guide regenerated: architecture rules updated."}}'
fi
exit 0
`

const (
	sentinelStart = "<!-- verikt:start -->"
	sentinelEnd   = "<!-- verikt:end -->"
	claudeHeader  = "<!-- verikt:generated -->\n"
)

// Target defines where and how to write guide output.
type Target interface {
	Name() string
	Write(projectDir, content string) error
}

// targetNames lists every valid --target selector, in output order.
var targetNames = []string{"all", "claude", "cursor", "copilot", "windsurf", "agents"}

// TargetNames returns the valid values for `verikt guide --target`.
func TargetNames() []string {
	return append([]string(nil), targetNames...)
}

// resolveTargets returns the targets matching the given selector.
//
// "all" means every agent the project actually uses, detected from the file each
// one owns. Writing all four unconditionally left .cursorrules, .windsurfrules and
// a copilot instructions file in repositories that use none of them, recreated on
// every guide run.
//
// When no marker is present there is no signal to go on — a freshly scaffolded
// project, which is the `verikt new` case — so every target is written. An
// explicit selector always wins: the user asked for that agent.
func resolveTargets(selector, projectDir string) ([]Target, error) {
	all := []Target{
		&claudeTarget{},
		&cursorTarget{},
		&sentinelTarget{name: "copilot", relPath: filepath.Join(".github", "copilot-instructions.md")},
		&sentinelTarget{name: "windsurf", relPath: ".windsurfrules"},
		// AGENTS.md is the cross-agent instructions file read by Codex,
		// Antigravity, OpenCode and others.
		&sentinelTarget{name: "agents", relPath: "AGENTS.md"},
	}

	if selector == "" || selector == "all" {
		inUse := make([]Target, 0, len(all))
		for _, t := range all {
			if targetInUse(t, projectDir) {
				inUse = append(inUse, t)
			}
		}
		if len(inUse) > 0 {
			return inUse, nil
		}
		return all, nil
	}

	for _, t := range all {
		if t.Name() == selector {
			return []Target{t}, nil
		}
	}
	return nil, fmt.Errorf("unknown guide target %q (valid: %s)", selector, strings.Join(targetNames, ", "))
}

// targetInUse reports whether the project already carries a file or directory
// that identifies this agent. These are agent configuration markers at fixed
// paths, not a scan of the source tree (ADR-008).
func targetInUse(t Target, projectDir string) bool {
	var markers []string
	switch target := t.(type) {
	case *claudeTarget:
		markers = []string{".claude"}
	case *cursorTarget:
		// .cursorrules is the legacy format; a project still carrying it uses
		// Cursor and needs verikt's section migrated out of it.
		markers = []string{".cursor", legacyCursorRules}
	case *sentinelTarget:
		markers = []string{target.relPath}
	default:
		return false
	}
	for _, rel := range markers {
		if _, err := os.Stat(filepath.Join(projectDir, rel)); err == nil {
			return true
		}
	}
	return false
}

// claudeTarget writes directly to .claude/rules/verikt.md.
type claudeTarget struct{}

func (t *claudeTarget) Name() string { return "claude" }

func (t *claudeTarget) Write(projectDir, content string) error {
	dir := filepath.Join(projectDir, ".claude", "rules")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("create claude rules dir: %w", err)
	}
	path := filepath.Join(dir, "verikt.md")
	return os.WriteFile(path, []byte(claudeHeader+content), 0o644)
}

// generateHooks creates hook scripts under .claude/hooks/ and registers them
// in .claude/settings.json via JSON-aware merge.
func generateHooks(projectDir string) error {
	hooksDir := filepath.Join(projectDir, ".claude", "hooks")
	if err := os.MkdirAll(hooksDir, 0o755); err != nil {
		return fmt.Errorf("create hooks dir: %w", err)
	}

	checkScript := filepath.Join(hooksDir, "verikt-check.sh")
	if err := os.WriteFile(checkScript, []byte(hookScriptCheck), 0o755); err != nil {
		return fmt.Errorf("write verikt-check.sh: %w", err)
	}

	refreshScript := filepath.Join(hooksDir, "verikt-guide-refresh.sh")
	if err := os.WriteFile(refreshScript, []byte(hookScriptGuideRefresh), 0o755); err != nil {
		return fmt.Errorf("write verikt-guide-refresh.sh: %w", err)
	}

	hooks := map[string]any{
		"PostToolUse": []any{
			map[string]any{
				"matcher": "Write|Edit",
				"hooks": []any{
					map[string]any{
						"type":    "command",
						"command": `"$CLAUDE_PROJECT_DIR"/.claude/hooks/verikt-check.sh`,
						"timeout": 10,
					},
				},
			},
		},
		"SessionStart": []any{
			map[string]any{
				"matcher": "startup",
				"hooks": []any{
					map[string]any{
						"type":    "command",
						"command": `"$CLAUDE_PROJECT_DIR"/.claude/hooks/verikt-guide-refresh.sh`,
						"timeout": 10,
					},
				},
			},
		},
	}

	return mergeClaudeSettingsJSON(projectDir, hooks)
}

// veriktHookScripts are the hook scripts verikt owns. A settings.json hook whose
// command references one of them is verikt's entry, even when an older verikt
// wrote it with a different matcher or timeout; every other hook is the user's.
var veriktHookScripts = []string{
	"/.claude/hooks/verikt-check.sh",
	"/.claude/hooks/verikt-guide-refresh.sh",
}

// mergeClaudeSettingsJSON reads .claude/settings.json, merges verikt's hook
// entries into it, and writes the result back atomically.
//
// A file verikt cannot parse is the user's, not a blank slate: treating it as
// empty replaced their whole configuration with verikt's hooks. So any parse
// error, or a "hooks" value of the wrong shape, returns an error and leaves the
// file untouched. Per event, user hooks are kept where they are and verikt's own
// entries are replaced in place, so repeated runs are idempotent.
func mergeClaudeSettingsJSON(projectDir string, hooks map[string]any) error {
	claudeDir := filepath.Join(projectDir, ".claude")
	settingsPath := filepath.Join(claudeDir, "settings.json")

	existing, err := readClaudeSettings(settingsPath)
	if err != nil {
		return err
	}
	before, err := json.Marshal(existing)
	if err != nil {
		return fmt.Errorf("marshal %s: %w", settingsPath, err)
	}

	existingHooks := map[string]any{}
	if raw, present := existing["hooks"]; present && raw != nil {
		m, ok := raw.(map[string]any)
		if !ok {
			return fmt.Errorf("%s: \"hooks\" must be a JSON object; verikt will not overwrite it", settingsPath)
		}
		existingHooks = m
	}

	for event, value := range hooks {
		desired, ok := value.([]any)
		if !ok {
			return fmt.Errorf("verikt hooks for %s must be a list", event)
		}
		var current []any
		if raw, present := existingHooks[event]; present && raw != nil {
			if current, ok = raw.([]any); !ok {
				return fmt.Errorf("%s: hooks.%s must be a JSON array; verikt will not overwrite it", settingsPath, event)
			}
		}
		existingHooks[event] = mergeHookEntries(current, desired)
	}
	existing["hooks"] = existingHooks

	// Re-marshalling reorders keys and reformats every field, so writing
	// unconditionally produced a large diff on a file the run did not actually
	// change. Compare semantically, since the byte form differs from a
	// hand-written file even when nothing was added.
	if after, err := json.Marshal(existing); err == nil && bytes.Equal(before, after) {
		return nil
	}

	if err := os.MkdirAll(claudeDir, 0o755); err != nil {
		return fmt.Errorf("create %s: %w", claudeDir, err)
	}
	return writeJSONAtomic(settingsPath, existing)
}

// readClaudeSettings returns the settings object at path: empty when the file
// is absent or blank, an error when it holds anything but a JSON object.
func readClaudeSettings(path string) (map[string]any, error) {
	data, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return map[string]any{}, nil
	}
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}
	if strings.TrimSpace(string(data)) == "" {
		return map[string]any{}, nil
	}
	var parsed any
	if err := json.Unmarshal(data, &parsed); err != nil {
		return nil, fmt.Errorf("parse %s: %w (fix or remove the file; verikt will not overwrite it)", path, err)
	}
	obj, ok := parsed.(map[string]any)
	if !ok {
		return nil, fmt.Errorf("parse %s: top-level value must be a JSON object; verikt will not overwrite it", path)
	}
	return obj, nil
}

// mergeHookEntries returns current with verikt's hook entries replaced by
// desired. desired goes where the first verikt entry was, keeping the file
// stable across runs, or at the end when there was none.
//
// A hook is verikt's when its command names a verikt script, or is a command
// desired registers; an entry identical to a desired one is verikt's too. User
// hooks, including ones sharing a matcher group with verikt's, are kept.
func mergeHookEntries(current, desired []any) []any {
	owned := map[string]bool{}
	for _, entry := range desired {
		for _, command := range hookCommands(entry) {
			owned[command] = true
		}
	}

	out := make([]any, 0, len(current)+len(desired))
	inserted := false
	for _, entry := range current {
		kept, hadVerikt := stripVeriktHooks(entry, owned)
		if !hadVerikt && containsEntry(desired, entry) {
			kept, hadVerikt = nil, true
		}
		if hadVerikt && !inserted {
			out = append(out, desired...)
			inserted = true
		}
		if kept != nil {
			out = append(out, kept)
		}
	}
	if !inserted {
		out = append(out, desired...)
	}
	return out
}

// stripVeriktHooks removes verikt's commands from a matcher group. It returns
// the group to keep (nil when nothing remains) and whether anything was removed.
// Entries of unknown shape are returned unchanged.
func stripVeriktHooks(entry any, owned map[string]bool) (any, bool) {
	group, ok := entry.(map[string]any)
	if !ok {
		return entry, false
	}
	inner, ok := group["hooks"].([]any)
	if !ok {
		return entry, false
	}
	remaining := make([]any, 0, len(inner))
	for _, h := range inner {
		if !isVeriktHook(h, owned) {
			remaining = append(remaining, h)
		}
	}
	if len(remaining) == len(inner) {
		return entry, false
	}
	if len(remaining) == 0 {
		return nil, true
	}
	kept := make(map[string]any, len(group))
	for k, v := range group {
		kept[k] = v
	}
	kept["hooks"] = remaining
	return kept, true
}

func isVeriktHook(h any, owned map[string]bool) bool {
	m, ok := h.(map[string]any)
	if !ok {
		return false
	}
	command, ok := m["command"].(string)
	if !ok {
		return false
	}
	if owned[command] {
		return true
	}
	for _, script := range veriktHookScripts {
		if strings.Contains(command, script) {
			return true
		}
	}
	return false
}

func containsEntry(entries []any, entry any) bool {
	for _, e := range entries {
		if reflect.DeepEqual(e, entry) {
			return true
		}
	}
	return false
}

// hookCommands extracts the command strings from one hook entry.
func hookCommands(entry any) []string {
	entryMap, ok := entry.(map[string]any)
	if !ok {
		return nil
	}
	inner, _ := entryMap["hooks"].([]any)
	var commands []string
	for _, h := range inner {
		hookMap, ok := h.(map[string]any)
		if !ok {
			continue
		}
		if command, ok := hookMap["command"].(string); ok {
			commands = append(commands, command)
		}
	}
	return commands
}

// writeJSONAtomic writes v as indented JSON to path through a temp file and a
// rename, so an interrupted write never leaves a truncated settings file. The
// file keeps its existing permissions.
func writeJSONAtomic(path string, v any) error {
	mode := os.FileMode(0o644)
	if info, err := os.Stat(path); err == nil {
		mode = info.Mode().Perm()
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), filepath.Base(path)+".tmp-*")
	if err != nil {
		return fmt.Errorf("create temp for %s: %w", path, err)
	}
	tmpName := tmp.Name()
	// Removing the temp file fails harmlessly once the rename has moved it.
	defer func() { _ = os.Remove(tmpName) }()

	enc := json.NewEncoder(tmp)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(v); err != nil {
		_ = tmp.Close() // the encode error is the one worth reporting
		return fmt.Errorf("marshal %s: %w", path, err)
	}
	if err := tmp.Chmod(mode); err != nil {
		_ = tmp.Close() // the chmod error is the one worth reporting
		return fmt.Errorf("chmod temp for %s: %w", path, err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	if err := os.Rename(tmpName, path); err != nil {
		return fmt.Errorf("replace %s: %w", path, err)
	}
	return nil
}

// writeGuideHash computes sha256 of verikt.yaml in projectDir and writes it
// to .verikt/.guide-hash for staleness detection by the SessionStart hook.
func writeGuideHash(projectDir string) error {
	yamlPath := filepath.Join(projectDir, "verikt.yaml")
	data, err := os.ReadFile(yamlPath)
	if errors.Is(err, os.ErrNotExist) {
		// No verikt.yaml — skip without error.
		return nil
	}
	if err != nil {
		return fmt.Errorf("read %s: %w", yamlPath, err)
	}

	sum := sha256.Sum256(data)
	hash := fmt.Sprintf("%x", sum)

	hashDir := filepath.Join(projectDir, ".verikt")
	if err := os.MkdirAll(hashDir, 0o755); err != nil {
		return fmt.Errorf("create .verikt dir: %w", err)
	}

	hashFile := filepath.Join(hashDir, ".guide-hash")
	if err := os.WriteFile(hashFile, []byte(hash), 0o644); err != nil {
		return fmt.Errorf("write .guide-hash: %w", err)
	}
	return nil
}

// sentinelTarget writes verikt's section into a file the user may share with
// other content (AGENTS.md, copilot-instructions.md, .windsurfrules). Only the
// text between GuideMarkers is replaced; everything else is preserved. When the
// markers are malformed the file is left untouched and an error is returned:
// appending a second section, as an earlier version did, left the agent reading
// two conflicting copies.
type sentinelTarget struct {
	name    string
	relPath string
}

func (t *sentinelTarget) Name() string { return t.name }

func (t *sentinelTarget) Write(projectDir, content string) error {
	path := filepath.Join(projectDir, t.relPath)

	existing, err := os.ReadFile(path) //nolint:gosec // projectDir joined with a fixed relative path
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("read %s: %w", t.relPath, err)
	}

	merged, err := ReplaceSection(string(existing), GuideMarkers, content)
	if err != nil {
		return fmt.Errorf("%s: %w; fix or remove the verikt markers by hand, verikt will not overwrite the file", t.relPath, err)
	}

	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("create dir for %s: %w", t.name, err)
	}
	return WriteFileAtomic(path, []byte(merged))
}

// cursorRulesPath is Cursor's project rules location (MDC format). The legacy
// single-file .cursorrules is deprecated by Cursor.
var cursorRulesPath = filepath.Join(".cursor", "rules", "verikt.mdc")

const legacyCursorRules = ".cursorrules"

// cursorFrontmatter marks the rule as always applied, matching the other
// always-loaded targets. An empty globs value is what Cursor writes for an
// always-applied rule.
const cursorFrontmatter = "---\n" +
	"description: Architecture rules for this project, generated by verikt guide from verikt.yaml\n" +
	"globs:\n" +
	"alwaysApply: true\n" +
	"---\n"

// cursorTarget writes .cursor/rules/verikt.mdc, a file verikt owns entirely,
// then migrates verikt's section out of a legacy .cursorrules file.
type cursorTarget struct {
	notices io.Writer
}

func (t *cursorTarget) Name() string { return "cursor" }

func (t *cursorTarget) Write(projectDir, content string) error {
	path := filepath.Join(projectDir, cursorRulesPath)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("create cursor rules dir: %w", err)
	}
	if err := WriteFileAtomic(path, []byte(cursorFrontmatter+claudeHeader+content)); err != nil {
		return fmt.Errorf("write %s: %w", cursorRulesPath, err)
	}
	return t.migrateLegacy(projectDir)
}

// migrateLegacy removes verikt's sentinel section from .cursorrules so Cursor
// does not load the rules twice. User content is never removed: a file with no
// verikt section is left alone, a file with malformed markers is left alone
// with a notice, and the file is deleted only when nothing but whitespace
// remains after removing verikt's section.
func (t *cursorTarget) migrateLegacy(projectDir string) error {
	path := filepath.Join(projectDir, legacyCursorRules)
	data, err := os.ReadFile(path) //nolint:gosec // projectDir joined with a fixed relative path
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("read %s: %w", legacyCursorRules, err)
	}

	remaining, removed, err := RemoveSection(string(data), GuideMarkers)
	if err != nil {
		t.notify("verikt: left %s untouched (%v). Cursor now reads %s; remove verikt's old section from %s by hand.",
			legacyCursorRules, err, cursorRulesPath, legacyCursorRules)
		return nil
	}
	if !removed {
		return nil
	}
	if strings.TrimSpace(remaining) == "" {
		if err := os.Remove(path); err != nil {
			return fmt.Errorf("remove %s: %w", legacyCursorRules, err)
		}
		t.notify("verikt: removed legacy %s (it held only verikt's section); Cursor now reads %s.", legacyCursorRules, cursorRulesPath)
		return nil
	}
	if err := WriteFileAtomic(path, []byte(remaining)); err != nil {
		return fmt.Errorf("write %s: %w", legacyCursorRules, err)
	}
	t.notify("verikt: moved verikt's section from %s to %s; your own content in %s was kept.", legacyCursorRules, cursorRulesPath, legacyCursorRules)
	return nil
}

func (t *cursorTarget) notify(format string, args ...any) {
	if t.notices == nil {
		return
	}
	// Notices are informational; a failed write to the notice stream must not
	// fail guide generation, whose files are already written.
	_, _ = fmt.Fprintf(t.notices, format+"\n", args...)
}
